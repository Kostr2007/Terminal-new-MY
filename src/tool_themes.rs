use crate::{
    palette::{self, Theme},
    ui,
};
use clap::Args;
use ratatui::style::Color;
use serde::Serialize;
use std::{
    fs,
    io::{self, Write},
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

#[derive(Args)]
pub struct Options {
    /// Export eza, bat, fzf and delta themes into this directory
    #[arg(long)]
    pub export: Option<PathBuf>,
    /// Compile the exported bat theme using an isolated bat cache
    #[arg(long, requires = "export")]
    pub build_bat: bool,
    /// Report original and effective text contrast; fail if effective contrast is below 4.5
    #[arg(long)]
    pub check_contrast: bool,
    #[arg(long, requires = "check_contrast")]
    pub json: bool,
}
#[derive(Serialize)]
pub struct Contrast {
    pub foreground: &'static str,
    pub background: &'static str,
    pub original: f64,
    pub effective: f64,
    pub adjusted: bool,
}
pub fn contrasts(theme: &Theme) -> Vec<Contrast> {
    [
        ("on_surface", "surface"),
        ("on_surface", "surface_container"),
        ("on_surface_variant", "surface_container"),
        ("primary", "surface_container"),
        ("tertiary", "surface_container"),
        ("error", "surface"),
        ("on_primary_container", "primary_container"),
        ("on_secondary_container", "secondary_container"),
    ]
    .into_iter()
    .map(|(fg, bg)| {
        let original = theme.contrast(fg, bg);
        let effective = palette::contrast(theme.accessible(fg, bg), theme.color(bg));
        Contrast {
            foreground: fg,
            background: bg,
            original,
            effective,
            adjusted: original < 4.5,
        }
    })
    .collect()
}
fn hex(color: Color) -> String {
    let Color::Rgb(r, g, b) = color else {
        unreachable!()
    };
    format!("#{r:02x}{g:02x}{b:02x}")
}
fn atomic(path: &Path, text: &str) -> io::Result<()> {
    let parent = path.parent().unwrap();
    fs::create_dir_all(parent)?;
    // Each process has its own temporary file; readers see complete old/new files.
    let tmp = path.with_extension(format!("tmp-{}", std::process::id()));
    let result = (|| {
        let mut file = fs::File::create(&tmp)?;
        file.write_all(text.as_bytes())?;
        fs::rename(&tmp, path)
    })();
    if result.is_err() {
        let _ = fs::remove_file(tmp);
    }
    result
}
pub fn export(theme: &Theme, path: &Path, build_bat: bool) -> io::Result<()> {
    let c = |role| hex(theme.color(role));
    let text = |role| hex(theme.accessible(role, "surface"));
    let eza = format!(
        "# Generated by tnmy from myt palette.json\nfilekinds:\n  normal: {{foreground: '{}' }}\n  directory: {{foreground: '{}', is_bold: true}}\n  symlink: {{foreground: '{}'}}\n  executable: {{foreground: '{}'}}\n",
        text("on_surface"),
        text("primary"),
        text("tertiary"),
        text("secondary")
    );
    atomic(&path.join("eza/theme.yml"), &eza)?;
    let mut xml = format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<plist version=\"1.0\"><dict><key>name</key><string>TerminalNewMY</string><key>settings</key><array><dict><key>settings</key><dict><key>background</key><string>{}</string><key>foreground</key><string>{}</string><key>selection</key><string>{}</string><key>caret</key><string>{}</string></dict></dict>",
        c("surface"),
        text("on_surface"),
        c("secondary_container"),
        text("primary")
    );
    for (scope, role) in [
        ("comment", "on_surface_variant"),
        ("keyword, storage", "primary"),
        ("string", "secondary"),
        ("constant.numeric, constant.language", "tertiary"),
        ("entity.name.function, support.function", "primary"),
        ("invalid", "error"),
    ] {
        xml.push_str(&format!("<dict><key>scope</key><string>{scope}</string><key>settings</key><dict><key>foreground</key><string>{}</string></dict></dict>",text(role)));
    }
    xml.push_str("</array></dict></plist>\n");
    atomic(&path.join("bat/themes/TerminalNewMY.tmTheme"), &xml)?;
    let fzf = format!(
        "--color=bg:{},fg:{},bg+:{},fg+:{},hl:{},hl+:{},pointer:{},marker:{},prompt:{},header:{},border:{}",
        c("surface"),
        text("on_surface"),
        c("secondary_container"),
        hex(theme.accessible("on_secondary_container", "secondary_container")),
        text("primary"),
        hex(theme.accessible("on_secondary_container", "secondary_container")),
        text("primary"),
        text("tertiary"),
        text("primary"),
        text("secondary"),
        c("outline")
    );
    atomic(&path.join("fzf.opts"), &fzf)?;
    // Distinct labels/foregrounds supplement backgrounds for added/removed lines.
    let delta = format!(
        "# Generated by tnmy\n[delta]\n    {} = true\n    syntax-theme = none\n    minus-style = \"{} {}\"\n    minus-emph-style = \"bold {} {}\"\n    plus-style = \"{} {}\"\n    plus-emph-style = \"bold {} {}\"\n    zero-style = \"{} {}\"\n    file-style = \"bold {}\"\n    hunk-header-style = \"{} {}\"\n",
        theme.mode,
        text("error"),
        c("surface"),
        text("error"),
        c("surface"),
        text("primary"),
        c("surface"),
        text("primary"),
        c("surface"),
        text("on_surface"),
        c("surface"),
        text("primary"),
        hex(theme.accessible("on_primary_container", "primary_container")),
        c("primary_container")
    );
    atomic(&path.join("delta.gitconfig"), &delta)?;
    // Argument vectors also work with Home Manager's delta wrapper, which
    // already supplies --config. Never pass a second --config to that wrapper.
    let mut delta_args = vec![format!("--{}", theme.mode), "--syntax-theme=none".into()];
    for (name, value) in [
        ("minus-style", format!("{} {}", text("error"), c("surface"))),
        (
            "minus-emph-style",
            format!("bold {} {}", text("error"), c("surface")),
        ),
        (
            "plus-style",
            format!("{} {}", text("primary"), c("surface")),
        ),
        (
            "plus-emph-style",
            format!("bold {} {}", text("primary"), c("surface")),
        ),
        (
            "zero-style",
            format!("{} {}", text("on_surface"), c("surface")),
        ),
        ("file-style", format!("bold {}", text("primary"))),
        (
            "hunk-header-style",
            format!(
                "{} {}",
                hex(theme.accessible("on_primary_container", "primary_container")),
                c("primary_container")
            ),
        ),
    ] {
        delta_args.push(format!("--{name}={value}"));
    }
    atomic(
        &path.join("delta.args"),
        &format!("{}\0", delta_args.join("\0")),
    )?;
    let manifest = serde_json::json!({"version":env!("CARGO_PKG_VERSION"),"mode":theme.mode,"source":theme.source,"density_default":format!("{:?}",ui::Density::default())});
    atomic(
        &path.join("manifest.json"),
        &serde_json::to_string_pretty(&manifest)?,
    )?;
    if build_bat {
        let status = Command::new("bat")
            .args(["cache", "--build"])
            .env("BAT_CONFIG_DIR", path.join("bat"))
            .env("BAT_CACHE_PATH", path.join("bat-cache"))
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::inherit())
            .status()?;
        if !status.success() {
            return Err(io::Error::other("bat cache build failed"));
        }
    }
    Ok(())
}
